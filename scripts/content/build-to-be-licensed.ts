import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = "public/walkthrough";
const OUTPUT = "docs/to_be_licensed.md";
const NOT_FOUND = "not found";

export interface LicenceRow {
  readonly file: string;
  readonly usedFor?: string;
  readonly holder?: string;
  readonly author?: string;
  readonly sourcePage?: string;
  readonly page?: string;
  readonly directUrl?: string;
  readonly widthPx?: number;
  readonly status?: string;
  readonly licence?: string;
  readonly permission?: string;
  readonly contactRoute?: string;
}

const isCc0 = (row: LicenceRow): boolean => row.status === "cc0" || /cc0/i.test(row.licence ?? "");
const isOpenFont = (row: LicenceRow): boolean => /open font license/i.test(row.licence ?? "");
const cell = (value: string | number | undefined): string => String(value ?? "not stated").replace(/\|/g, "\\|").replace(/\n/g, " ");
const holderOf = (row: LicenceRow): string => row.holder ?? row.author ?? "not stated";

export function rowsFrom(json: unknown): readonly LicenceRow[] {
  if (Array.isArray(json)) return json as LicenceRow[];
  const record = json as { rows?: unknown; assets?: unknown; items?: unknown };
  const rows = record.rows ?? record.assets ?? record.items;
  return Array.isArray(rows) ? (rows as LicenceRow[]) : [];
}

export function renderLicensingList(rows: readonly LicenceRow[], manifests: readonly string[]): string {
  const toLicense = rows.filter((row) => !isCc0(row) && !isOpenFont(row));
  const cc0 = rows.filter(isCc0);
  const openFonts = rows.filter(isOpenFont);
  const holders = [...new Set(toLicense.map(holderOf))].sort((left, right) => left.localeCompare(right));
  const lines = [
    "# To Be Licensed",
    "",
    `Generated by \`npm run content:to-be-licensed\` from ${manifests.map((name) => `\`${ROOT}/${name}\``).join(", ")}. Do not edit by hand.`,
    "",
    `${toLicense.length} third-party files from ${holders.length} holders need clearing before anything ships. ${cc0.length} CC0 assets and ${openFonts.length} open font files are listed at the end and need no licence.`,
    "",
  ];
  for (const holder of holders) {
    const held = toLicense.filter((row) => holderOf(row) === holder);
    const routes = [...new Set(held.map((row) => row.contactRoute ?? NOT_FOUND))];
    lines.push(`## ${holder}`, "", `Who to write to: ${routes.join("; ")}`, "", "| File | Used For | Source Page | Direct URL | Largest Width Used (px) | Permission Note |", "|---|---|---|---|---|---|");
    for (const row of held) lines.push(`| ${cell(row.file)} | ${cell(row.usedFor)} | ${cell(row.sourcePage ?? row.page)} | ${cell(row.directUrl)} | ${cell(row.widthPx)} | ${cell(row.permission)} |`);
    lines.push("");
  }
  lines.push("## CC0, No Licence Needed", "", "| File | Used For | Author | Page |", "|---|---|---|---|");
  for (const row of cc0) lines.push(`| ${cell(row.file)} | ${cell(row.usedFor)} | ${cell(holderOf(row))} | ${cell(row.sourcePage ?? row.page)} |`);
  lines.push("", "## Open Font License, No Licence Needed", "", "| File | Used For | Holder | Licence Text |", "|---|---|---|---|");
  for (const row of openFonts) lines.push(`| ${cell(row.file)} | ${cell(row.usedFor)} | ${cell(holderOf(row))} | ${cell(row.sourcePage ?? row.page)} |`);
  return `${lines.join("\n")}\n`;
}

function main(): void {
  const manifests = readdirSync(ROOT).filter((name) => /^manifest.*\.json$/.test(name)).sort();
  const rows = manifests.flatMap((name) => rowsFrom(JSON.parse(readFileSync(join(ROOT, name), "utf8"))));
  writeFileSync(OUTPUT, renderLicensingList(rows, manifests));
  console.log(`${OUTPUT}: ${rows.length} rows from ${manifests.join(", ")}`);
}

if (process.argv[1]?.replace(/\\/g, "/").endsWith("scripts/content/build-to-be-licensed.ts")) main();
