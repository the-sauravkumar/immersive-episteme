import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { REPO_ROOT } from "./_shared";
import { jpegSize, planStudyPhotos } from "./ingest-study-photos";

const ROOT = "public/walkthrough";
const OUTPUT = "docs/image-credits.md";
const STUDY_PHOTOS = "scripts/content/study-photos";
const PROPOSAL_FILES = ["media-proposals.json", "process-photo-proposals.json"];
export const CXA_APPROVAL = "Licensed for public use by CXA's approval (DR-118)";

export interface CreditRow {
  readonly file: string;
  readonly usedFor?: string;
  readonly holder?: string;
  readonly author?: string;
  readonly creditLine?: string;
  readonly sourcePage?: string;
  readonly page?: string;
  readonly directUrl?: string;
  readonly widthPx?: number;
  readonly status?: string;
  readonly licence?: string;
  readonly permission?: string;
}

export interface StudyPhotoCredit {
  readonly file: string;
  readonly credit: string;
  readonly licence: string;
  readonly sourcePage: string;
  readonly widthPx: number;
  readonly heightPx: number;
}

const isCc0 = (row: CreditRow): boolean => row.status === "cc0" || /cc0/i.test(row.licence ?? "");
const isOpenFont = (row: CreditRow): boolean => /open font license/i.test(row.licence ?? "");
const cell = (value: string | number | undefined): string => String(value ?? "not stated").replace(/\|/g, "\\|").replace(/\n/g, " ");
const holderOf = (row: CreditRow): string => row.holder ?? row.author ?? "not stated";

export function rowsFrom(json: unknown): readonly CreditRow[] {
  if (Array.isArray(json)) return json as CreditRow[];
  const record = json as { rows?: unknown; assets?: unknown; items?: unknown };
  const rows = record.rows ?? record.assets ?? record.items;
  return Array.isArray(rows) ? (rows as CreditRow[]) : [];
}

export function uncleared(rows: readonly CreditRow[]): readonly CreditRow[] {
  return rows.filter((row) => !isCc0(row) && !isOpenFont(row) && !(row.permission ?? "").startsWith(CXA_APPROVAL));
}

export function renderImageCredits(rows: readonly CreditRow[], manifests: readonly string[], photos: readonly StudyPhotoCredit[]): string {
  const thirdParty = rows.filter((row) => !isCc0(row) && !isOpenFont(row));
  const cc0 = rows.filter(isCc0);
  const openFonts = rows.filter(isOpenFont);
  const holders = [...new Set(thirdParty.map(holderOf))].sort((left, right) => left.localeCompare(right));
  const lines = [
    "# Image Credits",
    "",
    `Generated by \`npm run content:image-credits\` from ${manifests.map((name) => `\`${ROOT}/${name}\``).join(", ")} and the approved study photographs in \`content/review\`. Do not edit by hand.`,
    "",
    `Every image is licensed for public use by CXA's approval (DR-118): ${thirdParty.length} third-party files from ${holders.length} holders and ${photos.length} study photographs, each served at the size listed and credited as below. ${cc0.length} CC0 assets and ${openFonts.length} open font files are listed at the end.`,
    "",
  ];
  for (const holder of holders) {
    lines.push(`## ${holder}`, "", "| File | Used For | Credit | Source Page | Direct URL | Largest Width Used (px) | Licence Basis |", "|---|---|---|---|---|---|---|");
    for (const row of thirdParty.filter((candidate) => holderOf(candidate) === holder)) {
      lines.push(`| ${cell(row.file)} | ${cell(row.usedFor)} | ${cell(row.creditLine ?? holderOf(row))} | ${cell(row.sourcePage ?? row.page)} | ${cell(row.directUrl)} | ${cell(row.widthPx)} | ${cell(row.permission)} |`);
    }
    lines.push("");
  }
  lines.push("## Study Photographs", "", "Shown at the end of their tradition's route in both doors, at the full size of the file.", "", "| File | Credit | Licence | Source Page | Size (px) | Licence Basis |", "|---|---|---|---|---|---|");
  for (const photo of photos) lines.push(`| ${cell(photo.file)} | ${cell(photo.credit)} | ${cell(photo.licence)} | ${cell(photo.sourcePage)} | ${photo.widthPx} x ${photo.heightPx} | ${CXA_APPROVAL} |`);
  lines.push("", "## CC0, No Licence Needed", "", "| File | Used For | Author | Page |", "|---|---|---|---|");
  for (const row of cc0) lines.push(`| ${cell(row.file)} | ${cell(row.usedFor)} | ${cell(holderOf(row))} | ${cell(row.sourcePage ?? row.page)} |`);
  lines.push("", "## Open Font License, No Licence Needed", "", "| File | Used For | Holder | Licence Text |", "|---|---|---|---|");
  for (const row of openFonts) lines.push(`| ${cell(row.file)} | ${cell(row.usedFor)} | ${cell(holderOf(row))} | ${cell(row.sourcePage ?? row.page)} |`);
  return `${lines.join("\n")}\n`;
}

export function manifestNames(): string[] {
  return readdirSync(join(REPO_ROOT, ROOT)).filter((name) => /^manifest.*\.json$/.test(name)).sort();
}

export function manifestRows(manifests: readonly string[]): CreditRow[] {
  return manifests.flatMap((name) => rowsFrom(JSON.parse(readFileSync(join(REPO_ROOT, ROOT, name), "utf8"))));
}

export function studyPhotoCredits(): StudyPhotoCredit[] {
  const review = join(REPO_ROOT, "content", "review");
  const proposals = PROPOSAL_FILES.map((name) => join(review, name)).filter((path) => existsSync(path)).map((path) => JSON.parse(readFileSync(path, "utf8")) as unknown);
  return planStudyPhotos(...proposals).map((plan) => {
    const size = jpegSize(new Uint8Array(readFileSync(join(REPO_ROOT, STUDY_PHOTOS, plan.file))));
    if (!size) throw new Error(`${plan.file}: not a JPEG`);
    return { file: `${STUDY_PHOTOS}/${plan.file}`, credit: plan.metadata.credit, licence: plan.metadata.licence, sourcePage: plan.metadata.sourceUrl, widthPx: size.width, heightPx: size.height };
  });
}

function main(): void {
  const manifests = manifestNames();
  const rows = manifestRows(manifests);
  const open = uncleared(rows);
  if (open.length > 0) throw new Error(`Rows without a licence basis: ${open.map((row) => row.file).join(", ")}`);
  writeFileSync(join(REPO_ROOT, OUTPUT), renderImageCredits(rows, manifests, studyPhotoCredits()));
  console.log(`${OUTPUT}: ${rows.length} rows from ${manifests.join(", ")}`);
}

if (process.argv[1]?.replace(/\\/g, "/").endsWith("scripts/content/build-image-credits.ts")) main();
